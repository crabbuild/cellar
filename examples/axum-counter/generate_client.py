#!/usr/bin/env python3
"""Small fixture client generator: consumes this example's exported OpenAPI 3.1.

Supports object responses containing integer/string/boolean properties and
single named path parameters. Unsupported contracts fail explicitly. This is a
reproducible integration fixture, not a general OpenAPI generator.
"""
import json
import re
import sys
from pathlib import Path
api = json.loads(Path(sys.argv[1]).read_text())
assert api['openapi'] == '3.1.0'
lines = ['// Generated by generate_client.py from openapi.json. Do not edit.',
         'use anyhow::Result;', 'use serde::Deserialize;', '']
for name, schema in sorted(api['components']['schemas'].items()):
    assert schema['type'] == 'object'
    lines += ['#[derive(Debug, Deserialize)]', f'pub struct {name} {{']
    for field, value in sorted(schema['properties'].items()):
        kind = {'integer': 'u64' if value.get('minimum') == 0 else 'i64', 'string': 'String', 'boolean': 'bool'}[value['type']]
        assert re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', field)
        lines.append(f'    pub {field}: {kind},')
    lines += ['}', '']
for path, item in sorted(api['paths'].items()):
    for method, operation in sorted(item.items()):
        if method not in ['get', 'post']:
            continue
        name = operation['operationId'].split('.')[-1]
        name = re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()
        schema = operation['responses']['200']['content']['application/json']['schema']['$ref'].split('/')[-1]
        segments = path.split('/')[1:]
        assert segments.count('{name}') == 1
        lines += [f'pub async fn {name}(client: &reqwest::Client, base: &str, name: &str) -> Result<{schema}> {{',
                  '    let mut url = reqwest::Url::parse(base)?;',
                  '    { let mut path = url.path_segments_mut().map_err(|_| anyhow::anyhow!("base URL cannot have path segments"))?;',
                  '      path.pop_if_empty();']
        for segment in segments:
            lines.append('      path.push(name);' if segment == '{name}' else f'      path.push({json.dumps(segment)});')
        lines += ['    }', f'    Ok(client.{method}(url).send().await?.error_for_status()?.json().await?)', '}', '']
Path(sys.argv[2]).write_text('\n'.join(lines) + '\n')
