// Reference input is Protobuf JSON, independent of each language's model API.
// Preserve both its canonical meaning and reference wire bytes for native calls.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { fromJson, toBinary, toJson } from "@bufbuild/protobuf";
import { DurationSchema, EmptySchema, TimestampSchema } from "@bufbuild/protobuf/wkt";
import { AllTypesSchema, AllTypes_ChildSchema, RuntimeMappingsSchema } from "../fixtures/profile-generated/javascript/profile_pb.js";

export const schemas = Object.freeze({
  Echo: AllTypesSchema,
  Ping: EmptySchema,
  EchoChild: AllTypes_ChildSchema,
  EchoTimestamp: TimestampSchema,
  EchoDuration: DurationSchema,
  EchoMappings: RuntimeMappingsSchema,
});

export function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])]));
  }
  return value;
}

export async function corpus() {
  const cases = JSON.parse(await readFile(new URL("cases.json", import.meta.url), "utf8"));
  const names = new Set();
  return cases.map(entry => {
    if (!/^[a-z][a-z0-9-]{0,63}$/.test(entry.id) || names.has(entry.id) || !Object.hasOwn(schemas, entry.method)) {
      throw Error("Invalid portable-profile vector identity");
    }
    names.add(entry.id);
    const schema = schemas[entry.method];
    const message = fromJson(schema, entry.json);
    return {
      id: entry.id,
      method: entry.method,
      type: schema.typeName,
      json: entry.json,
      canonical: canonical(toJson(schema, message)),
      bytes: [...toBinary(schema, message)],
    };
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = JSON.stringify(await corpus(), null, 2) + "\n";
  const output = new URL("../fixtures/profile-vectors.json", import.meta.url);
  const module = new URL("corpus.ts", import.meta.url);
  const source = "// Copyright 2026 Cellar Project Authors. Licensed under Apache-2.0.\n\n"
    + "// Generated by profile/vectors.mjs. Shared semantic corpus; native wire vectors live separately.\n"
    + "export const vectors = " + JSON.stringify((await corpus()).map(({bytes, ...entry}) => entry), null, 2) + " as const;\n";
  if (process.argv[2] === "--write") {
    await writeFile(output, text);
    await writeFile(module, source);
  } else if (process.argv[2] !== "--check" || await readFile(output, "utf8") !== text || await readFile(module, "utf8") !== source) {
    throw Error("Regenerate profile vectors with node tools/rpc/profile/vectors.mjs --write");
  }
}
