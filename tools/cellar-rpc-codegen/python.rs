use anyhow::{ensure, Context, Result};
use cellar::sdk::rpc::Contract;
use heck::{ToSnakeCase, ToUpperCamelCase};
use prost_types::{DescriptorProto, FileDescriptorSet};
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
    path::Path,
    process::Command,
};

pub fn generate(output: &Path, descriptor: &FileDescriptorSet, contract: &Contract) -> Result<()> {
    // Validate importable spellings before invoking protoc or writing output.
    // Dynamic imports erase the namespace information used by type checkers.
    let mut types = BTreeMap::new();
    let mut imports = BTreeMap::new();
    let mut modules = BTreeSet::new();
    for (index, file) in descriptor.file.iter().enumerate() {
        let module = module_name(file.name.as_deref().context("unnamed descriptor file")?)?;
        ensure!(
            modules.insert(module.clone()),
            "generated Python module path collision: {module}"
        );
        let alias = format!("_messages_{index}");
        let import = format!("import {module} as {alias}");
        imports.insert(alias.clone(), import);
        let package = file.package.as_deref().unwrap_or_default();
        for message in &file.message_type {
            collect(package, &alias, message, &mut types)?;
        }
    }
    let directory = output.join("python");
    std::fs::create_dir_all(&directory)?;
    let mut command = Command::new("protoc");
    command
        .arg(format!(
            "--descriptor_set_in={}",
            output.join("contracts.binpb").display()
        ))
        .arg(format!("--python_out={}", directory.display()))
        .arg(format!("--pyi_out={}", directory.display()));
    for file in &descriptor.file {
        let name = file
            .name
            .as_deref()
            .context("descriptor filename is required")?;
        if !name.starts_with("google/protobuf/") {
            command.arg(name);
        }
    }
    let result = command
        .output()
        .context("Python generation requires protoc")?;
    ensure!(
        result.status.success(),
        "Python message generation failed: {}",
        String::from_utf8_lossy(&result.stderr)
    );
    for file in &descriptor.file {
        let name = file.name.as_deref().context("unnamed descriptor file")?;
        if name.starts_with("google/protobuf/") {
            continue;
        }
        let stub = directory.join(format!(
            "{}.pyi",
            name.trim_end_matches(".proto").replace('-', "_") + "_pb2"
        ));
        let code = std::fs::read_to_string(&stub)?;
        std::fs::write(stub, typed_mapping_initializers(&code))?;
    }

    for file in &descriptor.file {
        if file.service.is_empty() {
            continue;
        }
        let mut code = String::from("# Generated by cellar-rpc-codegen. Do not edit.\nfrom __future__ import annotations\nfrom typing import Protocol\nfrom cellar import Context\nfrom cellar_rpc import RpcClient, RpcMethod, RpcRegistration\n\n");
        let mut needed = BTreeSet::new();
        for service in &file.service {
            for method in &service.method {
                for reference in [&method.input_type, &method.output_type] {
                    let ty = types
                        .get(reference.as_deref().context("missing method type")?)
                        .context("unresolved Python method type")?;
                    needed.insert(ty.split('.').next().context("missing Python alias")?);
                }
            }
        }
        for alias in needed {
            writeln!(
                code,
                "{}",
                imports.get(alias).context("unresolved Python import")?
            )?;
        }
        let package = file.package.as_deref().unwrap_or_default();
        for service in &file.service {
            let original = service.name.as_deref().context("unnamed RPC service")?;
            let class = original.to_upper_camel_case();
            let mut rules = Vec::new();
            for method in &service.method {
                let original_method = method.name.as_deref().context("unnamed RPC method")?;
                let name = original_method.to_snake_case();
                let input = types
                    .get(method.input_type.as_deref().context("missing input type")?)
                    .context("unresolved Python input")?;
                let output = types
                    .get(
                        method
                            .output_type
                            .as_deref()
                            .context("missing output type")?,
                    )
                    .context("unresolved Python output")?;
                let symbol = format!("_{class}_{name}");
                let wire = format!("{package}.{original}/{original_method}");
                let limits = contract.limits();
                writeln!(code, "\n{symbol} = RpcMethod({wire:?}, {:?}, {name:?}, {input}, {output}, {}, {}, {}, {})", contract.digest(), limits.max_message_bytes, limits.max_depth, limits.max_elements, limits.max_decoded_slots)?;
                rules.push((name, input, output, symbol));
            }
            writeln!(code, "\nclass {class}Handler(Protocol):")?;
            for (name, input, output, _) in &rules {
                writeln!(
                    code,
                    "    async def {name}(self, request: {input}, ctx: Context) -> {output}: ..."
                )?;
            }
            writeln!(code, "\nclass {class}Client(RpcClient):\n    @classmethod\n    def bind(cls, context: Context, binding: str, name: str) -> {class}Client:\n        return cls(context, binding, name)")?;
            for (name, input, output, symbol) in &rules {
                writeln!(code, "\n    async def {name}(self, request: {input}, *, timeout_ms: int | None = None) -> {output}:\n        return await self._invoke({symbol}, request, timeout_ms=timeout_ms)")?;
            }
            writeln!(
                code,
                "\n{class}Registration = RpcRegistration([{}])",
                rules
                    .iter()
                    .map(|(_, _, _, symbol)| symbol.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            )?;
        }
        let filename = file
            .name
            .as_deref()
            .unwrap_or_default()
            .trim_end_matches(".proto")
            .replace('-', "_");
        let path = directory.join(format!("{filename}_cellar.py"));
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(path, code)?;
    }
    Ok(())
}

fn collect(
    package: &str,
    prefix: &str,
    message: &DescriptorProto,
    types: &mut BTreeMap<String, String>,
) -> Result<()> {
    let name = message.name.as_deref().context("unnamed message")?;
    ensure!(
        identifier(name),
        "message name is a reserved Python identifier"
    );
    let full = format!("{package}.{name}");
    let expression = format!("{prefix}.{name}");
    types.insert(format!(".{full}"), expression.clone());
    for nested in &message.nested_type {
        collect(&full, &expression, nested, types)?;
    }
    Ok(())
}

fn module_name(file: &str) -> Result<String> {
    let path = file
        .strip_suffix(".proto")
        .context("Python message path must end with .proto")?
        .replace('-', "_");
    let mut parts = path.split('/').map(str::to_string).collect::<Vec<_>>();
    parts
        .last_mut()
        .context("empty Python module path")?
        .push_str("_pb2");
    ensure!(
        parts.iter().all(|part| identifier(part)),
        "descriptor filename cannot be imported statically by Python: {file}"
    );
    Ok(parts.join("."))
}

fn typed_mapping_initializers(code: &str) -> String {
    // Protoc 34 emits a bare Mapping alternative for message initializers.
    // Describe its actual dictionary domain so strict application checks need
    // neither an Any-generic exception nor ignores in generated message stubs.
    if !code.contains(", _Mapping]") {
        return code.to_owned();
    }
    // A legal field such as `object` or `str` shadows that built-in inside a
    // generated message class. Qualify both types through a private import.
    format!(
        "import builtins as _cellar_rpc_builtins\n\n{}",
        code.replace(
            ", _Mapping]",
            ", _Mapping[_cellar_rpc_builtins.str, _cellar_rpc_builtins.object]]"
        )
    )
}

fn identifier(name: &str) -> bool {
    let mut bytes = name.bytes();
    bytes
        .next()
        .is_some_and(|byte| byte.is_ascii_alphabetic() || byte == b'_')
        && bytes.all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
        && ![
            "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
            "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
            "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise",
            "return", "try", "while", "with", "yield",
        ]
        .contains(&name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn python_module_names_are_static_and_match_protoc_normalization() {
        assert_eq!(module_name("counter.proto").unwrap(), "counter_pb2");
        assert_eq!(
            module_name("nested/my-counter.proto").unwrap(),
            "nested.my_counter_pb2"
        );
        assert_eq!(module_name("class.proto").unwrap(), "class_pb2");
        for path in [
            "class/counter.proto",
            "1counter.proto",
            "nested/a.b.proto",
            "counter",
        ] {
            assert!(module_name(path).is_err(), "accepted {path}");
        }
    }

    #[test]
    fn mapping_initializers_are_parameterized_without_changing_map_fields() {
        assert_eq!(
            typed_mapping_initializers("_Union[Child, _Mapping], _Mapping[str, Child]"),
            "import builtins as _cellar_rpc_builtins\n\n_Union[Child, _Mapping[_cellar_rpc_builtins.str, _cellar_rpc_builtins.object]], _Mapping[str, Child]"
        );
        assert_eq!(
            typed_mapping_initializers("_Mapping[str, Child]"),
            "_Mapping[str, Child]"
        );
    }
}
